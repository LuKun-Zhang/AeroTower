# 运行时懒加载
_PROVINCE_AIRPORTS_CACHE = None


def _build_province_airports():
    """构建省份 → 城市/机场名列表的映射"""
    result = {}
    for city, (lat, lng, province) in CITY_GEO.items():
        if province not in result:
            result[province] = []
        if city not in result[province]:
            result[province].append(city)
    return result


# 模糊匹配缓存
_FUZZY_CACHE = {}

def normalize_city_name(name):
    """将机场名模糊匹配到 CITY_GEO 中的城市名

    规则（按优先级）：
      1. 精确匹配
      2. name 包含城市名（如"长沙黄花"包含"长沙"）
      3. 城市名包含 name（如"浦东"被"上海"包含时放弃，仅保留规则2）

    返回:
        匹配到的城市名 或 None
    """
    if not name:
        return None
    if name in _FUZZY_CACHE:
        return _FUZZY_CACHE[name]
    if name in CITY_GEO:
        _FUZZY_CACHE[name] = name
        return name
    for city in CITY_GEO:
        if city in name:
            _FUZZY_CACHE[name] = city
            return city
    _FUZZY_CACHE[name] = None
    return None


def build_transit_cache_from_flights(flights):
    """从航班数据构建途经缓存（自动模糊匹配城市名）

    参数:
        flights: Flight 对象列表
    返回:
        {(dep_airport, arr_airport): set(途经省份)}
    """
    # 收集所有机场名并映射到 CITY_GEO 城市名
    name_map = {}  # raw_airport_name → city_name
    for f in flights:
        for raw in (getattr(f, 'departure_airport', ''), getattr(f, 'arrival_airport', '')):
            if raw and raw not in name_map:
                mapped = normalize_city_name(raw)
                if mapped:
                    name_map[raw] = mapped

    # 用映射后的城市名构建缓存
    cities = sorted(set(name_map.values()))
    city_cache = build_transit_cache(cities)

    # 转回原始机场名作 key
    result = {}
    for f in flights:
        dep_raw = getattr(f, 'departure_airport', '')
        arr_raw = getattr(f, 'arrival_airport', '')
        dep_city = name_map.get(dep_raw)
        arr_city = name_map.get(arr_raw)
        if dep_city and arr_city and dep_city != arr_city:
            t = city_cache.get((dep_city, arr_city))
            if t:
                result[(dep_raw, arr_raw)] = t
    return result


def get_province_airports(provinces):
    """返回指定省份下的所有城市/机场名列表

    参数:
        provinces: 省份名列表或 set
    返回:
        城市名列表
    """
    global _PROVINCE_AIRPORTS_CACHE
    if _PROVINCE_AIRPORTS_CACHE is None:
        _PROVINCE_AIRPORTS_CACHE = _build_province_airports()
    result = []
    for p in provinces:
        airports = _PROVINCE_AIRPORTS_CACHE.get(p, [])
        result.extend(airports)
    return result
