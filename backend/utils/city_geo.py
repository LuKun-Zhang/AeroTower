# ==================== 大圆路径计算 ====================

def _deg_to_rad(deg):
    return deg * math.pi / 180.0


def _rad_to_deg(rad):
    return rad * 180.0 / math.pi


def great_circle_sample(lat1, lng1, lat2, lng2, n=30):
    """在大圆路径上均匀采样 n 个点（含起终点）

    返回: [(lat, lng), ...]
    """
    lat1, lng1 = _deg_to_rad(lat1), _deg_to_rad(lng1)
    lat2, lng2 = _deg_to_rad(lat2), _deg_to_rad(lng2)

    # 球面距离
    d = math.acos(
        math.sin(lat1) * math.sin(lat2) +
        math.cos(lat1) * math.cos(lat2) * math.cos(lng2 - lng1)
    )
    if d < 1e-10:
        return [(_rad_to_deg(lat1), _rad_to_deg(lng1))]

    points = []
    for i in range(n + 1):
        f = i / n
        sin_d = math.sin(d)
        if sin_d < 1e-10:
            lat, lng = lat1, lng1
        else:
            a = math.sin((1 - f) * d) / sin_d
            b = math.sin(f * d) / sin_d
            x = a * math.cos(lat1) * math.cos(lng1) + b * math.cos(lat2) * math.cos(lng2)
            y = a * math.cos(lat1) * math.sin(lng1) + b * math.cos(lat2) * math.sin(lng2)
            z = a * math.sin(lat1) + b * math.sin(lat2)
            lat = math.atan2(z, math.sqrt(x * x + y * y))
            lng = math.atan2(y, x)
        points.append((_rad_to_deg(lat), _rad_to_deg(lng)))

    return points


def point_in_bounds(lat, lng, province):
    """判断点是否落在省份矩形边界盒内"""
    bounds = PROVINCE_BOUNDS.get(province)
    if not bounds:
        return False
    min_lat, max_lat, min_lng, max_lng = bounds
    return min_lat <= lat <= max_lat and min_lng <= lng <= max_lng


# ==================== 航线途经计算 + 缓存 ====================

def compute_route_transits(dep_city, arr_city):
    """计算单条航线途经的省份集合（不含起降省份）

    参数:
        dep_city: 出发城市名
        arr_city: 到达城市名
    返回:
        set(途经省份名)  或 空set
    """
    if dep_city == arr_city:
        return set()

    g1 = CITY_GEO.get(dep_city)
    g2 = CITY_GEO.get(arr_city)
    if not g1 or not g2:
        return set()

    # 采样
    points = great_circle_sample(g1[0], g1[1], g2[0], g2[1], n=30)

    transit = set()
    for lat, lng in points:
        for prov in PROVINCE_BOUNDS:
            if point_in_bounds(lat, lng, prov):
                transit.add(prov)

    # 排除起降省份本身（它们不算"途经"）
    transit.discard(g1[2])
    transit.discard(g2[2])

    # 同一个省内飞行：无途经省
    if g1[2] == g2[2]:
        return set()

    return transit


def build_transit_cache(cities):
    """预计算所有航线对的途经省份

    参数:
        cities: 系统中出现的所有城市名列表
    返回:
        {(dep, arr): set(途经省份)}
    """
    cache = {}
    for dep in cities:
        for arr in cities:
            if dep == arr:
                continue
            key = (dep, arr)
            t = compute_route_transits(dep, arr)
            if t:
                cache[key] = t
    return cache


def get_city_province(city):
    """获取城市所属省份（支持模糊匹配）"""
    if not city:
        return None
    mapped = normalize_city_name(city)
    if not mapped:
        return None
    g = CITY_GEO.get(mapped)
    return g[2] if g else None


def get_affected_flights_by_province(flights, weather_provinces, transit_cache):
    """根据天气异常省份，找出受影响航班

    规则：
      1. 起降机场在天气省份内的 → 直接受影响
      2. 航线途经天气省份的 → 途经受影响

    参数:
        flights: Flight 对象列表
        weather_provinces: set(受天气影响的省份)
        transit_cache: {(dep, arr): set(途经省份)}
    返回:
        {
            "direct": set(flight_id),   # 起降在天气省份
            "transit": set(flight_id),  # 途经天气省份
            "all": set(flight_id),      # 全部受影响
        }
    """
    weather_set = set(weather_provinces)
    direct = set()
    transit_affected = set()

    for f in flights:
        dep_prov = get_city_province(f.departure_airport)
        arr_prov = get_city_province(f.arrival_airport)

        # 起降省份直接受影响
        if dep_prov in weather_set or arr_prov in weather_set:
            direct.add(f.flight_id)
            continue

        # 查途经缓存
        key = (f.departure_airport, f.arrival_airport)
        route_provs = transit_cache.get(key, set())
        if route_provs & weather_set:
            transit_affected.add(f.flight_id)

    return {
        "direct": direct,
        "transit": transit_affected,
        "all": direct | transit_affected,
    }


