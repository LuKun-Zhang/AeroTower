  props: ["currentTime"],
  watch: {
    options: function () {
      this.myChart.setOption(this.options);
    },
    currentTime: function () {
      if (this.filteredMode && this.timeSlices.length > 0) {
        this._renderSlice(this.currentTime % this.timeSlices.length);
      } else {
        this._renderStatic(this.currentTime);
      }
    }
  },
  methods: {
    _renderSlice(idx) {
      var slice = this.timeSlices[idx] || [];
      var data = [];
      var airportSet = {};
      for (var i = 0; i < slice.length; i++) {
        var item = slice[i];
        var fromCoord = geoCoordMap[item.from];
        var toCoord = geoCoordMap[item.to];
        if (!fromCoord || !toCoord) continue;
        data.push({
          fromName: item.from,
          toName: item.to,
          id: i + 1,
          flightNo: item.flight_no || '',
          coords: [fromCoord, toCoord],
          effect: { period: (item.value || 5) * 3.5 },
          lineStyle: { normal: { color: color[i % color.length] } },
        });
        airportSet[item.from] = true;
        airportSet[item.to] = true;
      }
      // 生成机场标记
      var airports = [];
      for (var name in airportSet) {
        var coord = geoCoordMap[name];
        if (coord) {
          airports.push({ name: name, value: coord.concat([100]) });
        }
      }
      this.options.series[0].data = data;
      this.options.series[1].data = data;
      this.options.series[2].data = airports;
      this.options = { ...this.options };
    },
    _renderStatic(idx) {
      this.AerodromesList = require('../static/json/Aerodromes_A319');
      var AirlinesJson = require('../static/json/Airlines_A319');
      this.AirlinesList = AirlinesJson[idx % AirlinesJson.length];
      this.options.series[0].data = convertData(this.AirlinesList);
      this.options.series[1].data = convertData(this.AirlinesList);
      this.AerodromesList.map(function (dataItem) {
        if (geoCoordMap[dataItem.name] == undefined)
          alert(dataItem.name + "地图信息缺失");
      });
      this.options.series[2].data = this.AerodromesList.map(function (dataItem) {
        return {
          name: dataItem.name,
          value: geoCoordMap[dataItem.name].concat([dataItem.value]),
        };
      });
      this.options = { ...this.options };
    },
    async _loadMapSlices() {
      try {
        var res = await fetch('/api/schedule/map-data');
        var json = await res.json();
        if (json.code === 0 && json.data.filtered_mode && json.data.timeslices.length > 0) {
          this.timeSlices = json.data.timeslices;
          this.filteredMode = true;
          this.$emit('totalSlices', this.timeSlices.length);
          this.$emit('filteredData', { timeslices: this.timeSlices });
          this._renderSlice(this.currentTime % this.timeSlices.length);
        }
      } catch (e) {
        console.warn('[Map] API加载失败', e);
      }
    }
  },
  mounted () {
    this.myChart = echarts.init(this.$refs.echarts);
    this.myChart.setOption(this.options);
    this._renderStatic(0);
    this._loadMapSlices();
    var that = this;
    this._onResize = function() { that.myChart.resize(); };
    window.addEventListener('resize', this._onResize);
    this.myChart.on('click',function(params){
      for (var i = 0; i < that.AerodromesList.length; i++) {
        if(that.AerodromesList[i].name == params.name)
          if(that.AerodromesList[i].value == 0)
            that.AerodromesList[i].value = 100
          else
            that.AerodromesList[i].value = 0
          console.log(that.AerodromesList[i].name+":"+that.AerodromesList[i].value)
      }
      that.options = { ...that.options }
    })
  },
  beforeDestroy() {
    window.removeEventListener('resize', this._onResize);
    if (this.myChart) this.myChart.dispose();
  }
}
